#pragma once

/// @file ExecutionReport.hpp
/// Results returned to clients after submitting or cancelling an order.

#include "mx/core/Order.hpp"
#include "mx/core/Trade.hpp"

#include <string>
#include <vector>

namespace mx {

/// Outcome of processing one order. The quantities always satisfy
/// `quantity == filledQuantity + restingQuantity + cancelledQuantity`
/// for accepted orders.
struct ExecutionReport {
  OrderId orderId{kInvalidOrderId};
  std::string symbol;
  std::string trader;
  Side side{Side::Buy};
  OrderType type{OrderType::Limit};
  TimeInForce timeInForce{TimeInForce::GTC};
  Price price{0};
  Quantity quantity{0};
  Quantity filledQuantity{0};
  Quantity restingQuantity{0};    ///< Quantity left in the book (GTC limit orders only).
  Quantity cancelledQuantity{0};  ///< Unfilled quantity cancelled (IOC/FOK/market).
  OrderStatus status{OrderStatus::New};
  std::vector<Trade> trades;  ///< Trades generated by this order, in execution order.
  std::string message;        ///< Reject or cancel reason; empty otherwise.

  [[nodiscard]] bool accepted() const noexcept { return status != OrderStatus::Rejected; }
  [[nodiscard]] bool isResting() const noexcept { return restingQuantity > 0; }

  /// Volume-weighted average fill price in currency units (e.g. 150.25), or 0 if nothing filled.
  [[nodiscard]] double averageFillPrice() const noexcept;

  [[nodiscard]] static ExecutionReport fromOrder(const Order& order);
  [[nodiscard]] static ExecutionReport rejected(OrderId id, const OrderRequest& request,
                                                std::string reason);
};

struct CancelResult {
  bool success{false};
  OrderId orderId{kInvalidOrderId};
  std::string symbol;
  Quantity cancelledQuantity{0};
  std::string message;
};

}  // namespace mx
